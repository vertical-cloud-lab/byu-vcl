"""Build a gallery page, a contact sheet and an animated grid from scripts/render_cad.py output.

    python -I scripts/cad_gallery.py manifest.json renders/ out_dir/ [--cols 8]

Writes into out_dir:
    gallery.md          one row per design: turntable GIF, exploded GIF if any, provenance
    contact-sheet.png   every design's assembled still in one grid
    grid.gif            every turntable spinning at once (small tiles)
    grid.mp4            the same at a larger tile size, for slides (needs ffmpeg or imageio-ffmpeg)

Paths in gallery.md are relative to out_dir, so the page renders on GitHub as is.
"""

import argparse
import json
import os
import shutil
import subprocess
import tempfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, ImageSequence


def font(size, bold=False):
    try:
        return ImageFont.truetype("DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf", size)
    except OSError:
        return ImageFont.load_default()


def tile_frames(gif: Path, w: int, h: int, n: int):
    im = Image.open(gif)
    frames = [f.convert("RGB").resize((w, h), Image.LANCZOS) for f in ImageSequence.Iterator(im)]
    if not frames:
        return [Image.new("RGB", (w, h), "white")] * n
    # Resample to n frames so every tile completes one turn per loop.
    return [frames[int(i * len(frames) / n) % len(frames)] for i in range(n)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("manifest")
    ap.add_argument("renders")
    ap.add_argument("out")
    ap.add_argument("--cols", type=int, default=8)
    ap.add_argument("--title", default="Generative CAD across the Vertical Cloud Lab")
    ap.add_argument("--intro", default="", help="markdown paragraph placed under the title")
    ap.add_argument("--sheet-sections", nargs="*",
                    help="only these sections go into the contact sheet and grids (default: all)")
    args = ap.parse_args()

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    rdir = Path(args.renders)
    rel = os.path.relpath(rdir, out)
    everything = json.loads(Path(args.manifest).read_text())
    designs = [d for d in everything if (rdir / f"{d['id']}.gif").exists()]
    unrendered = [d for d in everything if not (rdir / f"{d['id']}.gif").exists()]

    def entry(i, d, rendered=True):
        repo = d.get("repo", "")
        src = d.get("source_paths") or []
        commit = d.get("commit", "")
        file_links = ", ".join(
            f"[`{Path(p).name}`](https://github.com/{repo}/blob/{commit[:7]}/{p})" for p in src[:4])
        if len(src) > 4:
            file_links += f" and {len(src) - 4} more"
        links = " · ".join(f"[{u.rstrip('/').split('/')[-2]} {u.rstrip('/').split('/')[-1]}]({u})"
                            for u in (d.get("links") or [])[:4])
        ls = [f"### {i}. {d.get('title', d['id'])}", "",
              f"**{repo.split('/')[-1]}** · first seen {d.get('first_seen', '?')}"
              + (f" · {d['versions']} versions" if d.get("versions") else "")
              + (f" · {d['parts']} parts" if d.get("assembly") and d.get("parts") else ""), "",
              d.get("system", ""), ""]
        if rendered:
            imgs = f"![{d['id']}]({rel}/{d['id']}.gif)"
            if (rdir / f"{d['id']}-exploded.gif").exists():
                imgs += f" ![{d['id']} exploded]({rel}/{d['id']}-exploded.gif)"
            ls += [imgs, ""]
        if file_links:
            ls.append(f"- Files: {file_links}")
        if d.get("generator"):
            ls.append(f"- Generated by: [`{d['generator']}`](https://github.com/{repo}/blob/{commit[:7]}/{d['generator']})")
        if d.get("evidence"):
            ls.append(f"- Provenance: {d['evidence']}")
        if links:
            ls.append(f"- Thread: {links}")
        ls.append("")
        return ls

    # gallery.md, grouped by section in the order sections first appear
    sections = list(dict.fromkeys(d.get("section", "Designs") for d in everything))
    lines = [f"# {args.title}", ""]
    if args.intro:
        lines += [args.intro, ""]
    lines += [f"{len(designs)} designs rendered, oldest first within each section. Each links to the files "
              "it was rendered from and to the issue or PR it came out of. Assemblies also get an exploded view.",
              ""]
    i = 0
    for sec in sections:
        group = [d for d in designs if d.get("section", "Designs") == sec]
        if not group:
            continue
        lines += [f"## {sec} ({len(group)})", ""]
        for d in group:
            i += 1
            lines += entry(i, d)
    if unrendered:
        lines += [f"## Not rendered ({len(unrendered)})", "",
                  "These exist only as generator scripts that need other repos' files or a different "
                  "environment to build, so they have no render here.", ""]
        for d in unrendered:
            i += 1
            lines += entry(i, d, rendered=False)
    (out / "gallery.md").write_text("\n".join(lines))

    if args.sheet_sections:
        designs = [d for d in designs if d.get("section", "Designs") in args.sheet_sections]

    # contact-sheet.png
    cols = args.cols
    tw, th = 240, 180
    rows = (len(designs) + cols - 1) // cols
    head = 60
    sheet = Image.new("RGB", (cols * tw, head + rows * th), "white")
    dr = ImageDraw.Draw(sheet)
    dr.text((12, 14), f"{args.title}: {len(designs)} designs", fill=(20, 20, 20), font=font(24, True))
    for i, d in enumerate(designs):
        im = Image.open(rdir / f"{d['id']}.png").convert("RGB").resize((tw, th), Image.LANCZOS)
        sheet.paste(im, ((i % cols) * tw, head + (i // cols) * th))
    sheet.save(out / "contact-sheet.png", optimize=True)

    # grid.gif and grid.mp4
    ffmpeg = shutil.which("ffmpeg")
    if not ffmpeg:
        try:
            import imageio_ffmpeg  # pip install imageio-ffmpeg ships a static binary
            ffmpeg = imageio_ffmpeg.get_ffmpeg_exe()
        except ImportError:
            ffmpeg = None
    n = 36
    for name, (w, h), fmt in (("grid.gif", (128, 96), "gif"), ("grid.mp4", (160, 120), "mp4")):
        if fmt == "mp4" and not ffmpeg:
            continue
        tiles = [tile_frames(rdir / f"{d['id']}.gif", w, h, n) for d in designs]
        canvas = []
        for k in range(n):
            c = Image.new("RGB", (cols * w, rows * h), "white")
            for i, t in enumerate(tiles):
                c.paste(t[k], ((i % cols) * w, (i // cols) * h))
            canvas.append(c)
        if fmt == "gif":
            pal = canvas[0].quantize(colors=128, method=Image.Quantize.MEDIANCUT)
            q = [c.quantize(palette=pal, dither=Image.Dither.NONE) for c in canvas]
            q[0].save(out / name, save_all=True, append_images=q[1:], duration=110, loop=0, optimize=True)
            subprocess.run(["gifsicle", "-O3", "--lossy=60", "-b", str(out / name)], capture_output=True)
        else:
            with tempfile.TemporaryDirectory() as td:
                for k, c in enumerate(canvas * 3):  # three turns
                    W, H = c.size
                    c.crop((0, 0, W - W % 2, H - H % 2)).save(f"{td}/f{k:04d}.png")
                subprocess.run([ffmpeg, "-y", "-loglevel", "error", "-framerate", "12", "-i", f"{td}/f%04d.png",
                                "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "26", str(out / name)], check=True)
    print(json.dumps({"designs": len(designs), "rows": rows, "cols": cols}))


if __name__ == "__main__":
    main()
