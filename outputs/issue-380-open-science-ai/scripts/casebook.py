#!/usr/bin/env python3
"""Compile the 121 case JSON files into one readable casebook (companies/CASEBOOK.md):
one section per organization with its openness path, outcome, numbers, the agent's customized
assessment and takeaway, licence/relicensing timeline, and its sources."""
import json, glob, re, os
GROUPS = {"A": "Commercial open source: data infrastructure and the relicensing cases", "B": "Commercial open source: platforms, developer and data/ML tools",
          "C": "Big Tech and AI labs", "D": "Hardware: open-hardware makers and closed comparators",
          "E": "Physical science: lab automation, cloud labs and AI-for-science companies", "F": "Physical science: scientific software and open-science infrastructure",
          "G": "Additive manufacturing, lab-automation incumbents and open-science publishing infrastructure (added after the video)"}
def money(v):
    try: v = float(v)
    except Exception: return None
    return f"${v/1e12:.2f}T" if v >= 1e12 else f"${v/1e9:.2f}B" if v >= 1e9 else f"${v/1e6:.1f}M"
out = ["# Casebook: organizations, one by one", "",
       "Generated by `scripts/casebook.py` from `companies/<group>/<slug>.json` (schema: [`SCHEMA.md`](SCHEMA.md); openness 0–4). "
       "Each entry's assessment and takeaway were written per organization by the research agents from the sources listed under it; "
       "numbers without a source are not used. `search_tool` says whether WebSearch or only WebFetch of known pages was available.", ""]
for g, title in GROUPS.items():
    files = sorted(glob.glob(f"companies/{g}/*.json"))
    out += [f"## {g}. {title} ({len(files)})", ""]
    for p in files:
        d = json.load(open(p))
        name = d.get("name") or os.path.basename(p)
        o0, o1 = d.get("openness_initial"), d.get("openness_current")
        lv = money(d.get("latest_value_usd")); lvt = d.get("latest_value_type"); lvd = d.get("latest_value_date")
        bits = [f"founded {d.get('founded_year')}" if d.get("founded_year") else None, d.get("hq_country"), f"origin: {d.get('origin')}" if d.get("origin") else None,
                f"openness {o0}→{o1}", d.get("ownership_status"), f"{lv} ({lvt}, {lvd})" if lv else None,
                f"funding {money(d.get('funding_total_usd'))}" if money(d.get("funding_total_usd")) else None,
                f"revenue {money(d.get('revenue_latest_usd'))} ({d.get('revenue_year')})" if money(d.get("revenue_latest_usd")) else None,
                f"confidence: {d.get('confidence')}", f"tool: {d.get('search_tool')}" if d.get("search_tool") else None]
        out += [f"### {name}", "", " · ".join(b for b in bits if b), ""]
        # computed metrics (this study)
        try:
            fy = int(str(d.get("founded_year"))[:4]); end = d.get("end_year")
            age = (int(str(end)[:4]) if end and str(d.get("still_operating")).lower() == "false" else 2026) - fy
        except Exception:
            age = None
        rel = d.get("relicensing_events") or []
        nc = sum(1 for e in rel if str(e.get("direction", "")).startswith("clos")); no = sum(1 for e in rel if str(e.get("direction", "")).startswith("open"))
        mult = None
        try:
            if d.get("latest_value_usd") and d.get("funding_total_usd"): mult = float(d["latest_value_usd"]) / float(d["funding_total_usd"])
        except Exception:
            pass
        comp = [f"age {age} yrs" if age is not None else None, f"{nc} closing / {no} opening moves",
                f"latest value ÷ funding raised ≈ {mult:.1f}×" if mult else None]
        out += ["*Computed:* " + " · ".join(c for c in comp if c), ""]
        if d.get("openness_effect_assessment"): out += [f"**What openness did.** {d['openness_effect_assessment']}", ""]
        if d.get("key_takeaway"): out += [f"**Takeaway.** {d['key_takeaway']}", ""]
        ev = []
        for e in d.get("relicensing_events") or []:
            ev.append(f"{e.get('year')}: {e.get('from')} → {e.get('to')} ({e.get('direction')})" + (f"; fork: {e.get('fork')}" if e.get("fork") else ""))
        for e in d.get("exit_events") or []:
            v = money(e.get("value_usd"))
            ev.append(f"{e.get('year')}: {e.get('type')}" + (f" {v}" if v else "") + (f", {e.get('counterparty')}" if e.get("counterparty") else ""))
        if ev: out += ["**Timeline.** " + "; ".join(str(x) for x in ev), ""]
        if d.get("risk_events"): out += ["**Risk events.** " + "; ".join(str(x) for x in d["risk_events"][:6]), ""]
        if d.get("robustness"): out += [f"**Robustness.** {d['robustness']}", ""]
        if d.get("physical_science_relevance"): out += [f"**Physical-science relevance.** {d['physical_science_relevance']}", ""]
        src = [s for s in (d.get("sources") or []) if s.get("url")]
        if src:
            out += ["<details><summary>Sources (" + str(len(src)) + ")</summary>", ""]
            out += [f"- [{(s.get('title') or s['url'])[:110]}]({s['url']})" + (f" ({s.get('publisher')}, {s.get('date')})" if s.get("publisher") or s.get("date") else "") for s in src]
            out += ["", "</details>", ""]
open("companies/CASEBOOK.md", "w").write("\n".join(out))
print("casebook lines", len(out), "chars", sum(len(x) for x in out))
