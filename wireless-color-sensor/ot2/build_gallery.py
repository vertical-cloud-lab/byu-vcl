def main(sha="main", width=300):
    frames = {f["name"][:-4]: f for f in json.load(open(
        os.path.join(HERE, "frames", "frames.json")))["frames"]}
    spectra = {s["file"][:-4]: s for s in json.load(open(
        os.path.join(HERE, "spectra", "spectra.json")))}

    out = ["# Every colour measurement, as a picture, a spectrum and a link", "",
           "Generated by `build_gallery.py`. Each row is one scan position: the frame",
           "the livestream was showing at the instant the sensor answered, the spectrum",
           "of that reading in the light-mixing house style, and the link back into the",
           "stream. The clock burned into each frame is the lab's local time (UTC-6) and",
           "is what the video offset was verified against.", ""]

    for run_file, title, when in RUN_TITLES:
        keys = [k for k, s in spectra.items() if s["run_file"] == run_file]
        keys.sort(key=lambda k: spectra[k]["t_first_utc"])
        if not keys:
            continue
        out += [f"## {title}", "", f"`{run_file}` · {when}", "",
                "| position | deck at that instant | spectrum | reading |",
                "| --- | --- | --- | --- |"]
        for k in keys:
            sp, fr = spectra[k], frames.get(k, {})
            frame_md = ""
            if fr:
                frame_md = (f'<img width="{width}" src="'
                            + RAW.format(sha=sha, path=f"frames/{k}.jpg") + '" />')
            plot_md = (f'<img width="{width}" src="'
                       + RAW.format(sha=sha, path=f"spectra/{k}.png") + '" />')
            note = SCENE.get(k, "")
            link = fr.get("url", "")
            cell = (f"**x = {sp['x']:.2f} mm**<br>mean total **{sp['mean_total']:.0f}**"
                    f"<br>{sp['t_first_utc'][11:19]} UTC"
                    + (f"<br>[open the stream here]({link})" if link else "")
                    + (f"<br>_{note}_" if note else "")
                    + (f"<br>overlay `{fr['overlay_local']}`" if fr else ""))
            out.append(f"| {sp['stage']} | {frame_md} | {plot_md} | {cell} |")
        out.append("")

    path = os.path.join(HERE, "measurement-gallery.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    print(f"{len(spectra)} rows -> {os.path.basename(path)}")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else "main")
