"""Assemble the per-measurement gallery: frame, spectrum, link, in one table.

Pulls together the three artefacts produced by ``stream_index.py``,
``frames_from_stream.py`` and ``plot_spectra.py`` so that a reader can go from
a number, to the picture of the deck at the instant that number was taken, to
the point in the livestream, without leaving the page.

``SCENE`` is the one hand-entered part: a note of what is visible in each
frame. It is a visual reading of the committed images, not something measured,
so it is kept here in the open rather than buried in a results file -- anyone
can click the link and disagree.
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RAW = "https://github.com/vertical-cloud-lab/byu-vcl/blob/{sha}/wireless-color-sensor/ot2/{path}?raw=true"

